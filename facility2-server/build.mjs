// facility2-server/build.mjs — emit explicit api/games route files.
// Each file is a thin Vercel Node function that imports the shared handler.
// Run: node facility2-server/build.mjs  (from repo root)
import { writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const routes = [
  'api/games/world.mjs',
  'api/games/accounts.mjs',
  'api/games/accounts/google.mjs',
  'api/games/accounts/google/callback.mjs',
  'api/games/rooms.mjs',
  'api/games/rooms/[code].mjs',
  'api/games/records.mjs',
  'api/games/[...all].mjs',
];
for (const rel of routes) {
  const p = resolve(root, rel);
  mkdirSync(dirname(p), { recursive: true });
  const depth = rel.split('/').length - 1; // api/games/... -> steps back to repo root
  const relHandler = '../'.repeat(depth) + 'facility2-server/vercel.mjs';
  writeFileSync(p, `// Generated by facility2-server/build.mjs — do not edit by hand.\nimport handler from '${relHandler}';\nexport default handler;\n`);
  console.log('wrote', rel, '->', relHandler);
}
console.log('done:', routes.length, 'route files');
