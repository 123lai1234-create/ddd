// kitchen-server/build.mjs — 產生明確的 api/games/kitchen 路由檔。
// 依 AGENTS.md：catchall 只吃單一段路徑，多段路徑一定要明確檔案路由。
// Run: node kitchen-server/build.mjs  (from repo root)
import { writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const routes = [
  'api/games/kitchen.mjs',
  'api/games/kitchen/[code].mjs',
];
for (const rel of routes) {
  const p = resolve(root, rel);
  mkdirSync(dirname(p), { recursive: true });
  const depth = rel.split('/').length - 1;
  const relHandler = '../'.repeat(depth) + 'kitchen-server/vercel.mjs';
  writeFileSync(p, `// Generated by kitchen-server/build.mjs — do not edit by hand.\nimport handler from '${relHandler}';\nexport default handler;\n`);
  console.log('wrote', rel, '->', relHandler);
}
console.log('done:', routes.length, 'route files');
